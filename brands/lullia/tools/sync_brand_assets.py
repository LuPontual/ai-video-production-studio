#!/usr/bin/env python3
"""Sync official LULLIA brand assets from the lullia-site repository, unmodified.

Extracts:
  - the official logo lockup (`<a class="brand brand-oficial">`: brand-simbolo + brand-lettering SVGs), byte-for-byte;
  - the CSS design tokens (:root custom properties);
  - the OFL-licensed brand fonts bundle (Bodoni Moda + Jost, base64) used by the site.

Output: brands/lullia/assets-generated/brand-assets.js (+ SOURCE.json with provenance).
Usage:  python3 brands/lullia/tools/sync_brand_assets.py /home/user/lullia-site
Never edit the generated logo markup by hand — re-run this script instead.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

site = Path(sys.argv[1] if len(sys.argv) > 1 else "/home/user/lullia-site")
out_dir = Path(__file__).resolve().parents[1] / "assets-generated"
out_dir.mkdir(exist_ok=True)

html = (site / "index.html").read_text(encoding="utf-8")
block = re.search(r'<a class="brand brand-oficial".*?</a>', html, re.S)
if not block:
    sys.exit("official logo block not found — site structure changed; do not substitute a redrawn logo")
svgs = re.findall(r"<svg.*?</svg>", block.group(0), re.S)
if len(svgs) != 2:
    sys.exit(f"expected 2 logo SVGs (simbolo + lettering), found {len(svgs)}")

root = re.search(r":root\s*\{(.*?)\}", html, re.S)
tokens = dict(re.findall(r"(--[a-z0-9-]+)\s*:\s*([^;]+);", root.group(1))) if root else {}

fonts_js = (site / "js" / "brief-fonts.js").read_text(encoding="utf-8")
fonts = json.loads(re.search(r"=\s*(\{.*\})", fonts_js, re.S).group(1))

commit = subprocess.run(["git", "-C", str(site), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()

payload = {
    "logo": {"simbolo": svgs[0], "lettering": svgs[1],
             "lockup_css": {"simbolo_height": 30, "lettering_height": 15, "gap": 12}},
    "tokens": tokens,
    "fonts": fonts,
}
(out_dir / "brand-assets.js").write_text(
    "// GENERATED by brands/lullia/tools/sync_brand_assets.py — do not edit.\n"
    f"// Source: LuPontual/lullia-site @ {commit}. Fonts: SIL Open Font License 1.1.\n"
    f"window.LULLIA_BRAND = {json.dumps(payload, ensure_ascii=False)};\n", encoding="utf-8")
(out_dir / "SOURCE.json").write_text(json.dumps({
    "repository": "LuPontual/lullia-site", "commit": commit,
    "logo_source": "index.html <a class=\"brand brand-oficial\"> (unmodified SVG markup)",
    "fonts_source": "js/brief-fonts.js (Bodoni Moda, Jost — OFL 1.1)",
    "fonts": sorted(fonts), "tokens": tokens}, indent=2, ensure_ascii=False), encoding="utf-8")
print(f"ok: logo svgs={len(svgs)} tokens={len(tokens)} fonts={sorted(fonts)} commit={commit[:10]}")
